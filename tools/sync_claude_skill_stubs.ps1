# sync_claude_skill_stubs.ps1 - makes every Helios project skill visible to Claude Code.
#
# Codex, Cursor, Gemini CLI and other hosts read `.agents/skills/<name>/SKILL.md`. Claude Code reads
# only `.claude/skills/<name>/SKILL.md`. A full copy drifts. This script writes one stub per skill:
# the frontmatter of the real file, verbatim, and a pointer to that file. `.agents/skills/` stays the
# only copy of each skill.
#
#   (default)   write missing or changed stubs, and remove generated stubs without a skill
#   -Check      change nothing; exit 1 when a stub is missing, changed, stale, or not generated
#
# Adapted from the Paramodo agent KB.
param(
  [switch]$Check,
  [string]$Root = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$marker = '<!-- Generated by tools/sync_claude_skill_stubs.ps1. Do not edit; edit the skill in .agents/skills/. -->'
$sourceRoot = Join-Path $Root '.agents/skills'
$stubRoot = Join-Path $Root '.claude/skills'

function Read-Normalized {
  param([Parameter(Mandatory)][string]$Path)

  return [System.IO.File]::ReadAllText($Path).Replace("`r`n", "`n")
}

function Get-ExpectedStub {
  param([Parameter(Mandatory)][string]$Name, [Parameter(Mandatory)][string]$SkillPath)

  $text = Read-Normalized $SkillPath
  $match = [regex]::Match($text, '\A---\n.*?\n---\n', [System.Text.RegularExpressions.RegexOptions]::Singleline)
  if (-not $match.Success) { throw "$SkillPath has no YAML frontmatter." }
  if ($match.Value -notmatch '(?m)^name:\s*"?' + [regex]::Escape($Name) + '"?\s*$') {
    throw "$SkillPath frontmatter 'name' does not match the folder name '$Name'."
  }
  if ($match.Value -notmatch '(?m)^description:\s*\S') { throw "$SkillPath frontmatter has no 'description'." }

  return @(
    $match.Value.TrimEnd("`n"),
    '',
    $marker,
    '',
    "Read ``.agents/skills/$Name/SKILL.md`` and follow it. That file is the only copy of this skill: Claude Code does not scan ``.agents/skills/``, so this stub makes the skill visible to it.",
    ''
  ) -join "`n"
}

$expected = [ordered]@{}
foreach ($dir in Get-ChildItem -Directory -LiteralPath $sourceRoot | Sort-Object Name) {
  $skill = Join-Path $dir.FullName 'SKILL.md'
  if (Test-Path -LiteralPath $skill -PathType Leaf) {
    $expected[$dir.Name] = Get-ExpectedStub -Name $dir.Name -SkillPath $skill
  }
}

$problems = [System.Collections.Generic.List[string]]::new()

foreach ($name in $expected.Keys) {
  $stub = Join-Path (Join-Path $stubRoot $name) 'SKILL.md'
  $current = if (Test-Path -LiteralPath $stub -PathType Leaf) { Read-Normalized $stub } else { $null }
  if ($current -eq $expected[$name]) { continue }

  if ($Check) {
    $problems.Add($(if ($null -eq $current) { "missing stub: .claude/skills/$name" } else { "changed stub: .claude/skills/$name" }))
    continue
  }
  New-Item -ItemType Directory -Force -Path (Split-Path -Parent $stub) | Out-Null
  [System.IO.File]::WriteAllText($stub, $expected[$name], [System.Text.UTF8Encoding]::new($false))
  Write-Output "wrote .claude/skills/$name"
}

if (Test-Path -LiteralPath $stubRoot) {
  foreach ($dir in Get-ChildItem -Directory -LiteralPath $stubRoot | Sort-Object Name) {
    if ($expected.Contains($dir.Name)) { continue }

    $stub = Join-Path $dir.FullName 'SKILL.md'
    $generated = (Test-Path -LiteralPath $stub -PathType Leaf) -and (Read-Normalized $stub).Contains($marker)
    if (-not $generated) {
      # A hand-written skill here is visible to Claude Code only. Never delete it silently.
      $problems.Add("not generated: .claude/skills/$($dir.Name) (move the skill to .agents/skills/)")
    } elseif ($Check) {
      $problems.Add("stale stub: .claude/skills/$($dir.Name)")
    } else {
      Remove-Item -LiteralPath $dir.FullName -Recurse -Force
      Write-Output "removed .claude/skills/$($dir.Name)"
    }
  }
}

if ($problems.Count -gt 0) {
  $problems | ForEach-Object { Write-Output $_ }
  Write-Output 'Run: pwsh -NoProfile -File tools/sync_claude_skill_stubs.ps1'
  exit 1
}

Write-Output "Claude Code skill stubs match .agents/skills ($($expected.Count) skills)."
exit 0
